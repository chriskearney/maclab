const MaxJSON = 4 << 20

var nameRE = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9_-]{0,79}$`)
var shaRE = regexp.MustCompile(`^[0-9a-f]{64}$`)

type Pin struct {
	Path   string `json:"path"`
	SHA256 string `json:"sha256"`
	Bytes  int64  `json:"bytes"`
}

// Value selects a whole JSON value, without shell interpolation. From is
// "inputs", "workflow" metadata, or an earlier successful phase; Pointer follows RFC6901.
type Value struct {
	From    string `json:"from"`
	Pointer string `json:"pointer"`
}
type Check struct {
	Pointer string          `json:"pointer"`
	Equals  json.RawMessage `json:"equals"`
}

// Helper uses one fixed protocol. Its reviewed source receives --binding <JSON>.
// There is no shell, arbitrary argv, expression evaluator, sudo, or remote exec.
// Existing owners with another interface need a reviewed adapter, not new flags.
type Helper struct {
	Python  Pin   `json:"python"`
	Source  Pin   `json:"source"`
	Closure []Pin `json:"closure"`
}
type Phase struct {
	ID          string                 `json:"id"`
	Kind        string                 `json:"kind"` // cache, upload, bind, helper, submit, wait
	TimeoutSec  int                    `json:"timeout_sec"`
	Mutates     bool                   `json:"mutates"`
	Scope       string                 `json:"scope,omitempty"`
	File        *Pin                   `json:"file,omitempty"`
	Template    json.RawMessage        `json:"template,omitempty"`
	Bind        map[string]Value       `json:"bind,omitempty"`
	Helper      string                 `json:"helper,omitempty"`
	InputPhase  string                 `json:"input_phase,omitempty"`
	Checks      []Check                `json:"checks,omitempty"`
	Recovery    bool                   `json:"recovery,omitempty"` // explicit branch; never auto-runs
	M1Admission *M1SubmissionAdmission `json:"m1_submission_admission,omitempty"`
}
type Plan struct {
	Schema  string            `json:"schema"`
	ID      string            `json:"id"`
	Device  string            `json:"device"`
	Inputs  json.RawMessage   `json:"inputs"`
	Helpers map[string]Helper `json:"helpers,omitempty"`
	Phases  []Phase           `json:"phases"`
}

// Authorization is retained operator evidence, not generated by this runner.
// One explicitly scoped receipt can cover the sequence. Resume never refreshes
// it or converts a stale readiness receipt into new permission.
type Authorization struct {
	Schema     string    `json:"schema"`
	PlanSHA256 string    `json:"plan_sha256"`
	Device     string    `json:"device"`
	ApprovedBy string    `json:"approved_by"`
	Evidence   Pin       `json:"evidence"`
	Scopes     []string  `json:"scopes"`
	ValidUntil time.Time `json:"valid_until"`
}
type Record struct {
	State               string          `json:"state"`
	Attempt             string          `json:"attempt,omitempty"`
	Started             time.Time       `json:"started,omitempty"`
	Finished            time.Time       `json:"finished,omitempty"`
	Seconds             float64         `json:"seconds"`
	Output              json.RawMessage `json:"output,omitempty"`
	OutputSHA256        string          `json:"output_sha256,omitempty"`
	Error               string          `json:"error,omitempty"`
	AuthorizationSHA256 string          `json:"authorization_sha256,omitempty"`
	RequestSHA256       string          `json:"request_sha256,omitempty"`
}
type State struct {
	Schema     string             `json:"schema"`
	PlanSHA256 string             `json:"plan_sha256"`
	ID         string             `json:"id"`
	Device     string             `json:"device"`
	Created    time.Time          `json:"created"`
	Records    map[string]*Record `json:"records"`
	Blocker    string             `json:"blocker,omitempty"`
}
type Backend interface {
	Submit(context.Context, api.JobSpec) (*api.Job, error)
	Upload(context.Context, string) (string, error)
	Job(context.Context, string) (*api.Job, error)
}
type Runner struct {
	Plan    Plan
	PlanSHA string
	Dir     string
	Backend Backend
	// RunHelper may be injected by CPU tests; production uses the fixed helper protocol.
	RunHelper func(context.Context, Helper, []byte, string) ([]byte, error)
	Now       func() time.Time
}

func Hash(b []byte) string { s := sha256.Sum256(b); return hex.EncodeToString(s[:]) }
func Decode(b []byte, v any) error {
	if len(b) > MaxJSON {
		return errors.New("JSON exceeds 4MiB ceiling")
	}
	if err := uniqueJSON(b); err != nil {
		return err
	}
	d := json.NewDecoder(bytes.NewReader(b))
	d.DisallowUnknownFields()
	if err := d.Decode(v); err != nil {
		return err
	}
	var extra any
	if err := d.Decode(&extra); err != io.EOF {
		return errors.New("trailing JSON")
	}
	return nil
}
func LoadPlan(path string) (*Runner, error) {
	b, err := readRegular(path, MaxJSON)
	if err != nil {
		return nil, err
	}
	var p Plan
	if err = Decode(b, &p); err != nil {
		return nil, err
	}
	if err = p.Validate(); err != nil {
		return nil, err
	}
	return &Runner{Plan: p, PlanSHA: Hash(b), Now: time.Now, RunHelper: RunHelper}, nil
}
func (p Plan) Validate() error {
	if p.Schema != "maclab.workflow/1" || !nameRE.MatchString(p.ID) || !nameRE.MatchString(p.Device) {
		return errors.New("invalid workflow schema/id/device")
	}
	var input any
	if err := decodeValue(p.Inputs, &input); err != nil {
		return fmt.Errorf("inputs: %w", err)
	}
	if len(p.Phases) == 0 || len(p.Phases) > 100 {
		return errors.New("need 1..100 phases")
	}
	known := map[string]bool{"inputs": true, "workflow": true}
	for _, x := range p.Helpers {
		for _, f := range append([]Pin{x.Python, x.Source}, x.Closure...) {
			if err := validPin(f); err != nil {
				return err
			}
		}
	}
	for _, s := range p.Phases {
		if !nameRE.MatchString(s.ID) || known[s.ID] {
			return fmt.Errorf("duplicate/invalid phase %q", s.ID)
		}
		if s.TimeoutSec < 1 || s.TimeoutSec > 7200 {
			return fmt.Errorf("%s: timeout must be 1..7200 seconds", s.ID)
		}
		if s.Mutates && !nameRE.MatchString(s.Scope) {
			return fmt.Errorf("%s: mutation needs an explicit scope", s.ID)
		}
		switch s.Kind {
		case "cache":
			if s.File == nil {
				return errors.New("cache needs file pin")
			}
			if err := validPin(*s.File); err != nil {
				return err
			}
			if s.Mutates {
				return errors.New("cache cannot claim a target mutation")
			}
		case "bind":
			if len(s.Template) == 0 {
				return errors.New("binding needs JSON template")
			}
			if s.Mutates {
				return errors.New("binding cannot claim a target mutation")
			}
		case "helper":
			if _, ok := p.Helpers[s.Helper]; !ok {
				return fmt.Errorf("unknown helper %s", s.Helper)
			}
			if !known[s.InputPhase] || (s.InputPhase == "inputs" || s.InputPhase == "workflow") {
				return errors.New("helper requires an earlier phase binding")
			}
		case "submit":
			if !s.Mutates || !known[s.InputPhase] || (s.InputPhase == "inputs" || s.InputPhase == "workflow") {
				return errors.New("submission needs mutation scope and earlier job binding")
			}
		case "upload":
			if s.Mutates || !known[s.InputPhase] || (s.InputPhase == "inputs" || s.InputPhase == "workflow") {
				return errors.New("upload requires earlier exact cache receipt and no target mutation")
			}
		case "wait":
			if s.Mutates || !known[s.InputPhase] || (s.InputPhase == "inputs" || s.InputPhase == "workflow") {
				return errors.New("wait requires an earlier submission")
			}
		default:
			return fmt.Errorf("unknown phase kind %q", s.Kind)
		}
		if s.M1Admission != nil {
			g := s.M1Admission
			if s.Kind != "submit" || p.Device != "m1" || !known[g.BootID.From] || g.BootID.From == "inputs" || g.BootID.From == "workflow" || g.MinimumLeaseSec < 2700 || g.MinimumLeaseSec > 7200 {
				return errors.New("M1 submission admission requires a prior genuine boot observation and 2700..7200-second lease")
			}
			if _, err := tokens(g.BootID.Pointer); err != nil {
				return err
			}
		}
		keys := make([]string, 0, len(s.Bind))
		for key := range s.Bind {
			keys = append(keys, key)
		}
		sort.Strings(keys)
		for i, key := range keys {
			for _, earlier := range keys[:i] {
				if key == earlier || earlier == "" || strings.HasPrefix(key, earlier+"/") {
					return errors.New("overlapping binding destinations")
				}
			}
		}
		for ptr, v := range s.Bind {
			if !known[v.From] {
				return fmt.Errorf("%s: forward/missing reference %s", s.ID, v.From)
			}
			if _, err := tokens(ptr); err != nil {
				return err
			}
			if _, err := tokens(v.Pointer); err != nil {
				return err
			}
		}
		if len(s.Bind) > 0 && s.Kind != "bind" {
			return errors.New("only bind phases accept data references")
		}
		for _, c := range s.Checks {
			if _, err := tokens(c.Pointer); err != nil {
				return err
			}
			if !json.Valid(c.Equals) {
				return errors.New("check value is not JSON")
			}
		}
		known[s.ID] = true
	}
	return nil
}
func validPin(p Pin) error {
	if !filepath.IsAbs(p.Path) || !shaRE.MatchString(p.SHA256) || p.Bytes < 1 || p.Bytes > 8<<30 {
		return fmt.Errorf("invalid exact file pin %s", p.Path)
	}
	return nil
}
func (r *Runner) now() time.Time {
	if r.Now != nil {
		return r.Now().UTC()
	}
	return time.Now().UTC()
}
func (r *Runner) Open() (*os.File, *State, error) {
	if !filepath.IsAbs(r.Dir) {
		return nil, nil, errors.New("state directory must be absolute")
	}
	if err := os.MkdirAll(r.Dir, 0700); err != nil {
		return nil, nil, err
	}
	st, err := os.Lstat(r.Dir)
	if err != nil || !st.IsDir() || st.Mode()&os.ModeSymlink != 0 || st.Mode().Perm()&0077 != 0 {
		return nil, nil, errors.New("state directory must be a private real directory")
	}
	l, err := os.OpenFile(filepath.Join(r.Dir, "lock"), os.O_CREATE|os.O_RDWR|syscall.O_NOFOLLOW, 0600)
	if err != nil {
		return nil, nil, err
	}
	if err = syscall.Flock(int(l.Fd()), syscall.LOCK_EX|syscall.LOCK_NB); err != nil {
		l.Close()
		return nil, nil, errors.New("workflow already has an active owner")
	}
	b, err := readRegular(filepath.Join(r.Dir, "state.json"), MaxJSON)
	if os.IsNotExist(err) {
		s := &State{Schema: "maclab.workflow-state/1", PlanSHA256: r.PlanSHA, ID: r.Plan.ID, Device: r.Plan.Device, Created: r.now(), Records: map[string]*Record{}}
		if err = r.save(s); err != nil {
			l.Close()
			return nil, nil, err
		}
		return l, s, nil
	}
	if err != nil {
		l.Close()
		return nil, nil, err
	}
	var s State
	if err = Decode(b, &s); err != nil {
		l.Close()
		return nil, nil, err
	}
	if s.Schema != "maclab.workflow-state/1" || s.PlanSHA256 != r.PlanSHA || s.ID != r.Plan.ID || s.Device != r.Plan.Device || s.Records == nil {
		l.Close()
		return nil, nil, errors.New("state/plan identity mismatch")
	}
	for id, rec := range s.Records {
		if rec.State == "done" {
			normalized, e := canonical(rec.Output)
			if e != nil {
				l.Close()
				return nil, nil, e
			}
			rec.Output = normalized
		}
		if rec.State == "done" && (Hash(rec.Output) != rec.OutputSHA256 || !json.Valid(rec.Output)) {
			l.Close()
			return nil, nil, fmt.Errorf("retained output drift: %s", id)
		}
	}
	return l, &s, nil
}
func (r *Runner) save(s *State) error {
	b, err := json.MarshalIndent(s, "", "  ")
	if err != nil {
		return err
	}
	if len(b)+1 > MaxJSON {
		return errors.New("aggregate workflow checkpoint exceeds 4MiB; previous durable intent retained, reconcile actual operation")
	}
	return atomicWrite(filepath.Join(r.Dir, "state.json"), append(b, '\n'))
}
func (r *Runner) authorized(path string, p Phase) (string, error) {
	b, err := readRegular(path, MaxJSON)
	if err != nil {
		return "", fmt.Errorf("authorization unavailable: %w", err)
	}
	var a Authorization
	if err = Decode(b, &a); err != nil {
		return "", err
	}
	if a.Schema != "maclab.workflow-authorization/1" || a.PlanSHA256 != r.PlanSHA || a.Device != r.Plan.Device || a.ApprovedBy == "" || (!a.ValidUntil.IsZero() && !r.now().Before(a.ValidUntil)) {
		return "", errors.New("authorization identity/scope expired or mismatched")
	}
	found := false
	for _, scope := range a.Scopes {
		if scope == p.Scope {
			found = true
		}
	}
	if !found {
		return "", fmt.Errorf("authorization does not cover %s", p.Scope)
	}
	if err = verifyPin(a.Evidence); err != nil {
		return "", fmt.Errorf("authorization evidence drift: %w", err)
	}
	return Hash(b), nil
}

// Run runs each phase once. Any interrupted/failed side effect blocks resume
// until retained authoritative evidence is reconciled; it is never retried.
func (r *Runner) Run(ctx context.Context, auth string, recovery bool) error {
	lock, s, err := r.Open()
	if err != nil {
		return err
	}
	defer lock.Close()
	for _, p := range r.Plan.Phases {
		if p.Recovery == recovery && p.Mutates {
			if rec := s.Records[p.ID]; rec != nil && rec.State != "done" {
				s.Blocker = p.ID + ": " + rec.State + "; actual outcome reconciliation required"
				_ = r.save(s)
				return errors.New(s.Blocker)
			}
		}
	}
	for _, p := range r.Plan.Phases {
		if p.Recovery != recovery {
			continue
		}
		if old := s.Records[p.ID]; old != nil {
			if old.State == "done" {
				if p.Kind == "cache" {
					var c Pin
					if err = json.Unmarshal(old.Output, &c); err != nil {
						return err
					}
					if err = verifyPin(c); err != nil {
						s.Blocker = p.ID + ": cached bytes no longer match; " + err.Error()
						_ = r.save(s)
						return errors.New(s.Blocker)
					}
				}
				refresh := false
				if p.Kind == "upload" {
					for _, later := range r.Plan.Phases {
						if later.Kind == "submit" && later.Recovery == recovery && s.Records[later.ID] == nil {
							refresh = true
						}
					}
				}
				if !refresh {
					continue
				}
				// Content upload is idempotent, not a device-side mutation. Refresh before
				// a still-unsubmitted job because old CAS receipts are not GC leases.
			} else {
				if p.Mutates || p.Kind == "helper" {
					s.Blocker = fmt.Sprintf("%s: %s; reconcile actual outcome before retry; recovery branch remains explicit", p.ID, old.State)
					_ = r.save(s)
					return errors.New(s.Blocker)
				}
				archived, _ := json.Marshal(old)
				if err = atomicWrite(filepath.Join(r.Dir, "attempt-"+p.ID+"-"+old.Attempt+".json"), archived); err != nil {
					return err
				}
			}
		}
		authSHA := ""
		if p.Mutates {
			authSHA, err = r.authorized(auth, p)
			if err != nil {
				s.Blocker = p.ID + ": " + err.Error()
				_ = r.save(s)
				return errors.New(s.Blocker)
			}
		}
		rec := &Record{State: "running", Attempt: randomID(), Started: r.now(), AuthorizationSHA256: authSHA}
		s.Records[p.ID] = rec
		s.Blocker = ""
		// Persist intent BEFORE even the first external side effect.
		if err = r.save(s); err != nil {
			return err
		}
		phaseCtx, cancel := context.WithTimeout(ctx, time.Duration(p.TimeoutSec)*time.Second)
		out, e := r.execute(phaseCtx, s, p)
		cancel()
		rec.Finished = r.now()
		rec.Seconds = rec.Finished.Sub(rec.Started).Seconds()
		if e == nil {
			e = checks(out, p.Checks)
		}
		if e != nil {
			rec.State = "uncertain"
			if !p.Mutates {
				rec.State = "failed"
			}
			rec.Error = e.Error()
			s.Blocker = p.ID + ": " + e.Error()
			if err = r.save(s); err != nil {
				return err
			}
			return errors.New(s.Blocker)
		}
		out, e = canonical(out)
		if e != nil {
			return e
		}
		rec.Output = out
		rec.OutputSHA256 = Hash(out)
		rec.State = "done"
		if err = r.save(s); err != nil {
			return err
		}
	}
	return nil
}
func (r *Runner) execute(ctx context.Context, s *State, p Phase) ([]byte, error) {
	switch p.Kind {
	case "cache":
		return r.cache(ctx, *p.File)
	case "bind":
		var doc any
		if err := decodeValue(p.Template, &doc); err != nil {
			return nil, err
		}
		keys := make([]string, 0, len(p.Bind))
		for ptr := range p.Bind {
			keys = append(keys, ptr)
		}
		sort.Strings(keys)
		for _, ptr := range keys {
			v := p.Bind[ptr]
			raw, err := r.value(s, v)
			if err != nil {
				return nil, err
			}
			if err = set(&doc, ptr, raw); err != nil {
				return nil, err
			}
		}
		return json.Marshal(doc)
	case "helper":
		in, err := r.value(s, Value{From: p.InputPhase})
		if err != nil {
			return nil, err
		}
		b, err := json.Marshal(in)
		if err != nil {
			return nil, err
		}
		s.Records[p.ID].RequestSHA256 = Hash(b)
		if err = r.save(s); err != nil {
			return nil, err
		}
		return r.RunHelper(ctx, r.Plan.Helpers[p.Helper], b, filepath.Join(r.Dir, p.ID+"-"+s.Records[p.ID].Attempt))
	case "upload":
		if r.Backend == nil {
			return nil, errors.New("lab client backend is not configured")
		}
		raw, err := r.value(s, Value{From: p.InputPhase})
		if err != nil {
			return nil, err
		}
		b, _ := json.Marshal(raw)
		var pin Pin
		if err = json.Unmarshal(b, &pin); err != nil {
			return nil, err
		}
		if pin.Path != filepath.Join(r.Dir, "cache", pin.SHA256) {
			return nil, errors.New("upload only consumes this workflow's verified cache")
		}
		if err = copyPinned(ctx, pin, nil); err != nil {
			return nil, err
		}
		actual, err := r.Backend.Upload(ctx, pin.Path)
		if err != nil {
			return nil, err
		}
		if actual != pin.SHA256 {
			return nil, errors.New("uploaded artifact hash mismatch")
		}
		if err = copyPinned(ctx, pin, nil); err != nil {
			return nil, err
		}
		return json.Marshal(map[string]any{"sha256": actual, "bytes": pin.Bytes, "cas_gc_lease": false})
	case "submit":
		if r.Backend == nil {
			return nil, errors.New("lab client backend is not configured")
		}
		raw, err := r.value(s, Value{From: p.InputPhase})
		if err != nil {
			return nil, err
		}
		b, _ := json.Marshal(raw)
		var spec api.JobSpec
		if err = Decode(b, &spec); err != nil {
			return nil, err
		}
		if spec.Device != r.Plan.Device || spec.Baseline || spec.Publish || len(spec.OMTAllow) > 0 {
			return nil, errors.New("job device mismatch or forbidden baseline/publish/OMT waiver")
		}
		if spec.Kernel == "" && spec.InstalledManifest == "" {
			return nil, errors.New("workflow needs exact kernel artifact or installed manifest")
		}
		if spec.Source != "" || spec.Build != "" {
			return nil, errors.New("freeze source/build to an exact artifact before submission")
		}
		if spec.Kernel != "" && !shaRE.MatchString(spec.Kernel) {
			return nil, errors.New("kernel must be exact sha256")
		}
		if spec.InstalledManifest != "" && !shaRE.MatchString(spec.InstalledManifest) {
			return nil, errors.New("installed manifest must be exact sha256")
		}
		s.Records[p.ID].RequestSHA256 = Hash(b)
		if err = r.save(s); err != nil {
			return nil, err
		}
		var j *api.Job
		if p.M1Admission != nil {
			admitted, ok := r.Backend.(M1AdmittingBackend)
			if !ok {
				return nil, errors.New("explicit M1 admission needs the reviewed standalone backend")
			}
			v, e := r.value(s, p.M1Admission.BootID)
			if e != nil {
				return nil, e
			}
			boot, ok := v.(string)
			if !ok || boot == "" {
				return nil, errors.New("M1 admission boot observation is missing")
			}
			j, err = admitted.SubmitM1(ctx, spec, boot, p.M1Admission.MinimumLeaseSec)
		} else {
			j, err = r.Backend.Submit(ctx, spec)
		}
		if err != nil {
			return nil, err
		}
		if j == nil || j.ID == "" {
			return nil, errors.New("submission returned no job identity")
		}
		if err = matchSubmitted(spec, j.Spec); err != nil {
			return nil, err
		}
		return json.Marshal(j)
	case "wait":
		if r.Backend == nil {
			return nil, errors.New("lab client backend is not configured")
		}
		var j api.Job
		raw, err := r.value(s, Value{From: p.InputPhase})
		if err != nil {
			return nil, err
		}
		b, _ := json.Marshal(raw)
		if err = json.Unmarshal(b, &j); err != nil || j.ID == "" {
			return nil, errors.New("wait lacks real job identity")
		}
		for {
			actual, err := r.Backend.Job(ctx, j.ID)
			if err != nil {
				return nil, err
			}
			if actual == nil || actual.ID != j.ID || actual.Spec.Device != r.Plan.Device {
				return nil, errors.New("job identity drift")
			}
			if !reflect.DeepEqual(actual.Spec, j.Spec) {
				return nil, errors.New("retained submitted job specification drift")
			}
			if err = r.checkSubmissionBinding(s, p.InputPhase, actual.Spec); err != nil {
				return nil, err
			}
			if actual.State == api.JobDone {
				if actual.Canceled || actual.Outcome != api.OutcomePass {
					return nil, fmt.Errorf("job %s finished %s; restoration must be inspected, never salvaged as PASS", j.ID, actual.Outcome)
				}
				return json.Marshal(actual)
			}
			select {
			case <-ctx.Done():
				return nil, ctx.Err()
			case <-time.After(time.Second):
			}
		}
	}
	return nil, errors.New("unsupported operation")
}
func (r *Runner) value(s *State, v Value) (any, error) {
	b := r.Plan.Inputs
	if v.From == "workflow" {
		b, _ = json.Marshal(map[string]string{"id": r.Plan.ID, "device": r.Plan.Device, "plan_sha256": r.PlanSHA})
	}
	if v.From != "inputs" && v.From != "workflow" {
		rec := s.Records[v.From]
		if rec == nil || rec.State != "done" || Hash(rec.Output) != rec.OutputSHA256 {
			return nil, fmt.Errorf("unverified/missing dependency %s", v.From)
		}
		b = rec.Output
	}
	var doc any
	if err := decodeValue(b, &doc); err != nil {
		return nil, err
	}
	return get(doc, v.Pointer)
}
func checks(raw []byte, cs []Check) error {
	if !json.Valid(raw) || len(raw) > MaxJSON {
		return errors.New("phase output is not bounded JSON")
	}
	var doc any
	if err := decodeValue(raw, &doc); err != nil {
		return err
	}
	for _, c := range cs {
		got, err := get(doc, c.Pointer)
		if err != nil {
			return err
		}
		var want any
		_ = decodeValue(c.Equals, &want)
		if !reflect.DeepEqual(got, want) {
			return fmt.Errorf("evidence assertion failed at %s", c.Pointer)
		}
	}
	return nil
}
func tokens(ptr string) ([]string, error) {
	if ptr == "" {
		return nil, nil
	}
	if !strings.HasPrefix(ptr, "/") {
		return nil, errors.New("JSON pointer must start with /")
	}
	ts := strings.Split(ptr[1:], "/")
	for i, t := range ts {
		for j := 0; j < len(t); j++ {
			if t[j] == '~' && (j+1 == len(t) || (t[j+1] != '0' && t[j+1] != '1')) {
				return nil, errors.New("invalid JSON pointer escape")
			}
			if t[j] == '~' {
				j++
			}
		}
		ts[i] = strings.ReplaceAll(strings.ReplaceAll(t, "~1", "/"), "~0", "~")
	}
	return ts, nil
}
func get(doc any, ptr string) (any, error) {
	ts, err := tokens(ptr)
	if err != nil {
		return nil, err
	}
	for _, t := range ts {
		m, ok := doc.(map[string]any)
		if !ok {
			return nil, fmt.Errorf("pointer traverses non-object: %s", ptr)
		}
		doc, ok = m[t]
		if !ok {
			return nil, fmt.Errorf("missing evidence pointer: %s", ptr)
		}
	}
	return doc, nil
}
func set(doc *any, ptr string, value any) error {
	ts, err := tokens(ptr)
	if err != nil {
		return err
	}
	if len(ts) == 0 {
		*doc = value
		return nil
	}
	cur := *doc
	for _, t := range ts[:len(ts)-1] {
		m, ok := cur.(map[string]any)
		if !ok {
			return errors.New("binding traverses non-object")
		}
		cur, ok = m[t]
		if !ok {
			return errors.New("binding target must already exist")
		}
	}
	m, ok := cur.(map[string]any)
	if !ok {
		return errors.New("binding target is not an object")
	}
	if _, ok = m[ts[len(ts)-1]]; !ok {
		return errors.New("binding target must already exist")
	}
	m[ts[len(ts)-1]] = value
	return nil
}
func randomID() string {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		panic(err)
	}
	return hex.EncodeToString(b[:])
}

func canonical(b []byte) ([]byte, error) {
	if err := uniqueJSON(b); err != nil {
		return nil, err
	}
	if len(b) > MaxJSON {
		return nil, errors.New("JSON exceeds ceiling")
	}
	var v any
	d := json.NewDecoder(bytes.NewReader(b))
	d.UseNumber()
	if err := d.Decode(&v); err != nil {
		return nil, err
	}
	var extra any
	if err := d.Decode(&extra); err != io.EOF {
		return nil, errors.New("trailing JSON")
	}
	return json.Marshal(v)
}

func decodeValue(b []byte, v *any) error {
	if err := uniqueJSON(b); err != nil {
		return err
	}
	d := json.NewDecoder(bytes.NewReader(b))
	d.UseNumber()
	return d.Decode(v)
}

// Only server's existing OMT normalization may extend a reviewed request. The
// resulting full stored spec is frozen and must remain byte-for-byte semantic
// identity at every later poll. No kernel/manifest/holder/cmdline substitution.
func matchSubmitted(want, got api.JobSpec) error {
	w, g := want, got
	w.Tests = nil
	g.Tests = nil
	if !reflect.DeepEqual(w, g) {
		return errors.New("submitted job does not match exact reviewed request")
	}
	if len(got.Tests) < len(want.Tests) || len(got.Tests) > len(want.Tests)+1 {
		return errors.New("submitted test list changed")
	}
	for i, t := range want.Tests {
		actual := got.Tests[i]
		if t.Builtin == "omarchy-m-test" {
			t.GUI = true
			if t.TimeoutSec == 0 {
				t.TimeoutSec = 900
			}
		}
		if !reflect.DeepEqual(t, actual) {
			return errors.New("submitted requested test changed")
		}
	}
	if len(got.Tests) > len(want.Tests) {
		extra := got.Tests[len(want.Tests)]
		if !reflect.DeepEqual(extra, api.TestSpec{Name: "omarchy-m-test", Builtin: "omarchy-m-test", GUI: true, TimeoutSec: 900}) {
			return errors.New("unexpected server-added test")
		}
		for _, t := range want.Tests {
			if t.Builtin == "omarchy-m-test" {
				return errors.New("duplicate OMT")
			}
		}
	}
	return nil
}
func (r *Runner) checkSubmissionBinding(s *State, phaseID string, spec api.JobSpec) error {
	for _, phase := range r.Plan.Phases {
		if phase.ID == phaseID && phase.Kind == "submit" {
			value, e := r.value(s, Value{From: phase.InputPhase})
			if e != nil {
				return e
			}
			b, _ := json.Marshal(value)
			var want api.JobSpec
			if e = Decode(b, &want); e != nil {
				return e
			}
			return matchSubmitted(want, spec)
		}
	}
	return errors.New("wait/reconciliation lacks actual submission phase")
}

// Ambiguous duplicate keys cannot be admitted as one authorization or identity
// by this decoder and interpreted differently by a downstream helper.
func uniqueJSON(b []byte) error {
	if len(b) > MaxJSON {
		return errors.New("JSON exceeds ceiling")
	}
	d := json.NewDecoder(bytes.NewReader(b))
	d.UseNumber()
	var walk func(int) error
	walk = func(depth int) error {
		if depth > 64 {
			return errors.New("JSON nesting exceeds bound")
		}
		t, e := d.Token()
		if e != nil {
			return e
		}
		switch t {
		case json.Delim('{'):
			seen := map[string]bool{}
			for d.More() {
				token, e := d.Token()
				if e != nil {
					return e
				}
				key, ok := token.(string)
				if !ok || seen[key] {
					return errors.New("duplicate or invalid JSON object key")
				}
				seen[key] = true
				if e = walk(depth + 1); e != nil {
					return e
				}
			}
			_, e = d.Token()
			return e
		case json.Delim('['):
			for d.More() {
				if e = walk(depth + 1); e != nil {
					return e
				}
			}
			_, e = d.Token()
			return e
		}
		return nil
	}
	if e := walk(0); e != nil {
		return e
	}
	if _, e := d.Token(); e != io.EOF {
		return errors.New("trailing JSON")
	}
	return nil
}
