// Package mesa stages exact split packages for job-owned diagnostic processes.
// It never installs packages or changes a user's desktop/session environment.
package mesa

import "github.com/iconidentify/maclab/internal/api"

const Schema = 1
const GLProbeSHA = "24007754c92e05220edc4645702853ac86c0ff5d98c084da126955ccdd4d6e82"
const VKProbeSHA = "e4a7b8d50c10d1cc3bf40c1dcaf9e74cd566ebb1901857e84b06256bbdf0d40d"
const OfficialArchiveSHA = "f209493b34e13e2985b1752c147a33a9a45e3e2eac99eb9606ae5a664c252f99"
const Semantics = "staged diagnostic: pinned packages ran only in job-owned processes; the desktop kept installed Mesa; not installed-desktop qualification"
const MaxCompressed int64 = 256 << 20
const MaxExpanded int64 = 2 << 30
const MaxFile int64 = 512 << 20
const MaxEntries = 50000

type File struct {
	SHA256  string `json:"sha256,omitempty"`
	Size    int64  `json:"size"`
	Link    string `json:"link,omitempty"` // safe relative link; no hardlinks
	Package string `json:"package"`
}
type Package struct {
	api.MesaPackage
	PkgBase       string `json:"pkgbase"`
	Version       string `json:"version"` // .PKGINFO pkgver including pkgrel and epoch
	Arch          string `json:"arch"`
	PKGInfoSHA256 string `json:"pkginfo_sha256"`
}
type Tool struct {
	Path   string `json:"path"`
	SHA256 string `json:"sha256"`
}

// Paths under Root in Files are clean relative archive paths. No path aliases
// outside Root are allowed. Providers contains canonical regular-file relative
// paths for egl, gallium and vulkan; loaders are independently frozen at runtime.
type Manifest struct {
	Schema           int               `json:"schema"`
	Job              string            `json:"job"`
	Prefix           string            `json:"prefix"`
	Root             string            `json:"root"`
	Packages         []Package         `json:"packages"`
	Files            map[string]File   `json:"files"`
	Probes           map[string]Tool   `json:"probes"`
	Providers        map[string]string `json:"providers"`
	VulkanJSONSHA256 string            `json:"vulkan_json_sha256"`
	EGLJSONSHA256    string            `json:"egl_json_sha256"`
	VulkanJSON       string            `json:"vulkan_json"`
	EGLJSON          string            `json:"egl_json"`
}

// RuntimePlan is generated by the root agent after staging in the actual job
// boot. It is private root-owned input, never a free-form user script.
type RuntimePlan struct {
	Schema              int               `json:"schema"`
	Job                 string            `json:"job"`
	BootID              string            `json:"boot_id"`
	Kernel              string            `json:"kernel"`
	CmdlineSHA256       string            `json:"cmdline_sha256"`
	ManifestPath        string            `json:"manifest_path"`
	ManifestSHA256      string            `json:"manifest_sha256"`
	GUIUser             string            `json:"gui_user"`
	GUIUID              int               `json:"gui_uid"`
	GUIGID              int               `json:"gui_gid"`
	GUIHome             string            `json:"gui_home"`
	GUIEnv              map[string]string `json:"gui_env"`
	OfficialGPU         bool              `json:"official_gpu"`
	SigningPublicSHA256 string            `json:"signing_public_sha256,omitempty"`
}
