# ---------------------------------------------------------------- small fs helpers

def lst(path):
    """lstat or None (missing, or a parent is not a directory). Never follows the final symlink."""
    try:
        return os.lstat(path)
    except (FileNotFoundError, NotADirectoryError):
        return None


def ftype(st):
    if st is None:
        return 'absent'
    m = st.st_mode
    return 'f' if stat.S_ISREG(m) else 'd' if stat.S_ISDIR(m) else 'l' if stat.S_ISLNK(m) else 'o'


def sorted_scandir(path):
    with os.scandir(path) as it:
        return sorted(it, key=lambda e: e.name)


def copy_file(src, dst, mode=0o600, b2=False):
    """Stream src -> new file dst (O_EXCL, no symlink follow either side), fsync. Returns (sha, b2|None, n)."""
    h = hashlib.sha256()
    hb = hashlib.blake2b(digest_size=64) if b2 else None
    n = 0
    sfd = os.open(src, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC)
    try:
        c.need(stat.S_ISREG(os.fstat(sfd).st_mode), 'not a regular file: %s' % src)
        dfd = os.open(dst, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_CLOEXEC, mode)
        try:
            while True:
                b = os.read(sfd, 1 << 20)
                if not b:
                    break
                h.update(b)
                if hb:
                    hb.update(b)
                view = memoryview(b)
                while view:
                    view = view[os.write(dfd, view):]
                n += len(b)
            os.fsync(dfd)
        finally:
            os.close(dfd)
    finally:
        os.close(sfd)
    return h.hexdigest(), (hb.hexdigest() if hb else None), n


def makedirs(path, mode=0o700):
    """mkdir -p without following symlinked components that we create; fsync each new dir's parent."""
    path = str(path)
    if os.path.isdir(path) and not os.path.islink(path):
        return
    parent = os.path.dirname(path)
    if parent and parent != path:
        makedirs(parent, mode)
    os.mkdir(path, mode)
    c.fsync_dir(parent)


