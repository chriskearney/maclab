def entry_block(menu, e):
    """Stripped raw lines after an entry header up to the next entry header or the lab block."""
    out = []
    for line in menu.lines[e.idx + 1:]:
        s = line.strip()
        if s.startswith('/') or s.startswith(limine.LAB_BEGIN):
            break
        out.append(s)
    return out


def is_auto_entry(menu, e):
    """Inside the limine-entry-tool generated block (entry or any ancestor carries the generator comment)."""
    x = e
    while x is not None:
        blk = entry_block(menu, x)
        if AUTO_KERNEL in blk or AUTO_OS in blk:
            return True
        x = x.parent
    return False


def package_uki(rel, names):
    """Candidate package whose installer writes this UKI path (EFI/Linux/<CUSTOM_UKI_NAME>_<pkgname>.efi)."""
    for n in sorted(names):
        if re.fullmatch(r'efi/linux/[^/]+_' + re.escape(n.lower()) + r'\.efi', rel.lower()):
            return n
    return None


def analyse_default(esp, cand_names):
    raw, info = pf.default_entry(esp)
    menu = limine.Menu(raw)
    d = menu.default()
    kv = [s.split('comment: Kernel version: ', 1)[1].strip() for s in entry_block(menu, d)
          if s.startswith('comment: Kernel version: ')]
    pkg = package_uki(info['path'], cand_names)
    info.update(leaf=d.name, kernel_version=kv[0] if kv else None, auto_block=is_auto_entry(menu, d),
                owned_by_package_uki=pkg is not None, uki_package=pkg,
                pin_ok=(info['pin_b2'] is None or info['pin_b2'] == info['uki_b2']))
    info['auto_entry'] = bool(info['auto_block'] or pkg)
    return raw, menu, info


def lab_block(raw):
    m = limine.Menu(raw)
    if m.lab is None:
        return None
    return '\n'.join(m.lines[m.lab[0]:m.lab[1] + 1])


# ---------------------------------------------------------------- misc live facts

def unit_props(unit):
    r = c.run([c.BIN('systemctl'), 'show', unit, '--property=' + ','.join(UNIT_PROPS)], timeout=30)
    props = dict(line.split('=', 1) for line in r.stdout.decode('utf-8', 'replace').splitlines() if '=' in line)
    return {k: props.get(k) for k in UNIT_PROPS}


def systemd_etc():
    root = c.P('/etc/systemd/system')
    out = {}
    if ftype(lst(root)) != 'd':
        return out
    for rel, path, st in walk_tree(root):
        if rel == '.':
            continue
        out[rel] = {'type': ftype(st), 'target': os.readlink(path) if stat.S_ISLNK(st.st_mode) else None,
                    'ino': st.st_ino}
    return out


def efivars():
    d = c.P('/sys/firmware/efi/efivars')
    return {n: os.path.lexists(d / ('%s-%s' % (n, EFIVAR_GUID))) for n in EFIVARS}


def snapshots():
    d = c.P('/.snapshots')
    if ftype(lst(d)) != 'd':
        return []
    return sorted(int(e.name) for e in sorted_scandir(d) if e.name.isdigit())


def machine_id():
    p = c.P('/etc/machine-id')
    if ftype(lst(p)) != 'f':
        return None
    v = c.read_small(p, 4096).decode().strip()
    return v if re.fullmatch(r'[0-9a-f]{32}', v) else None


def limine_history(manifest):
    mid = machine_id()
    if not mid:
        return {}
    pre = mid + '/limine_history/'
    return {rel: e['sha256'] for rel, e in sorted(manifest.items()) if rel.startswith(pre)}


def known_good_refs():
    d = c.P(KNOWN_GOOD_DIR)
    out = {}
    if ftype(lst(d)) != 'd':
        return out
    for e in sorted_scandir(d):
        if e.name.startswith('known-good.json'):
            p = KNOWN_GOOD_DIR + '/' + e.name
            st = os.lstat(e.path)
            out[p] = c.sha_file(e.path)[0] if stat.S_ISREG(st.st_mode) else 'type:' + ftype(st)
    return out


def modules_listing():
    d = c.P('/usr/lib/modules')
    return [e.name for e in sorted_scandir(d)] if ftype(lst(d)) == 'd' else []


def module_owners(krel):
    r = c.run([c.BIN('pacman'), '-Qqo', '/usr/lib/modules/' + krel], check=False, timeout=60)
    return sorted(r.stdout.decode().split()) if r.returncode == 0 else []


def module_record(krel):
    p = c.P('/usr/lib/modules/' + krel)
    st = lst(p)
    if st is None:
        return {'present': False, 'type': 'absent', 'owned_by': [], 'keep_marker': False, 'tree_sha256': None,
                'entries': 0, 'bytes': 0}, None
    if not stat.S_ISDIR(st.st_mode):
        return {'present': True, 'type': ftype(st), 'owned_by': module_owners(krel), 'keep_marker': False,
                'tree_sha256': None, 'entries': 1, 'bytes': 0,
                'target': os.readlink(p) if stat.S_ISLNK(st.st_mode) else None}, None
    info, rows = tree_map(p)
    return {'present': True, 'type': ftype(st), 'owned_by': module_owners(krel),
            'keep_marker': os.path.lexists(p / '.keep-local-kernel'), **info}, rows


def root_free(ctx):
    v = test_override(ctx, 'test_root_free')
    if v is not None:
        return v
    s = os.statvfs(ctx.run_dir)
    return s.f_bavail * s.f_frsize


# ---------------------------------------------------------------- capture

def capture(ctx):
    cfg = ctx.config
    final = ctx.run_dir / 'capture'
    c.need(not os.path.lexists(final), 'capture already exists for this run (refusing to overwrite truth)')
    part = ctx.run_dir / '.capture.partial'
    if os.path.lexists(part):
        shutil.rmtree(part)      # our own unfinished copy from an interrupted capture (never system state)
    cand = {p['name']: p for p in cfg['candidates']}
    orig = {p['name']: p for p in cfg['originals']}
    for n in cand:
        c.need(n in orig, 'candidate %s has no originals entry (baseline unknown)' % n)
    names = sorted(set(cand) | set(orig))
    regen = cfg.get('regenerated_on_target', DEPMOD_OUTPUTS)

    # -- packages
    packages_all = c.pacman_all()
    versions = {n: packages_all.get(n) for n in names}
    db = {}
    packages = {}
    for n in names:
        v = versions[n]
        if v is None:
            packages[n] = {'version': None, 'mtree_sha256': None, 'files': []}
            continue
        db[n] = local_db(n, v)
        packages[n] = {'version': v, 'mtree_sha256': db[n]['mtree_sha256'], 'files': ['/' + f for f in db[n]['files']]}

    # -- original-archive proof (refuse before copying anything)
    originals_verified, archives = {}, {}
    for n, o in sorted(orig.items()):
        ver = o.get('version')
        if ver is None:
            c.need(versions[n] is None, '%s is installed (%s) but config original says absent' % (n, versions[n]))
            continue
        c.need(versions[n] == ver, 'installed %s is %s, config original %s' % (n, versions[n], ver))
        if not o.get('file'):
            c.need(n not in cand, 'missing original archive for changing package ' + n)
            continue
        path = ctx.run_dir / 'originals' / o['file']
        c.need(os.path.lexists(path), 'missing original archive for %s: %s' % (n, o['file']))
        a = scan_archive(path, hash_payload=True)
        check_archive_identity(a, o, 'original')
        originals_verified[n] = prove_original(ctx, o, db[n], a, regen)
        archives['original:' + n] = a

    # -- candidate archives: krels, units, backup= paths, unowned conflicts
    owned = all_owned_paths()
    conflicts, ask = [], []
    for n, p in sorted(cand.items()):
        path = ctx.run_dir / 'pkgs' / p['file']
        c.need(os.path.lexists(path), 'missing candidate archive: ' + p['file'])
        a = scan_archive(path)
        check_archive_identity(a, p, 'candidate')
        archives['candidate:' + n] = a
        for m in a['members']:
            if m['type'] == 'd' or m['name'] in owned:
                continue
            if lst(c.P('/' + m['name'])) is not None:
                ask.append(('/' + m['name'], n))
    unowned = owners_unowned(sorted({p for p, _ in ask}))
    conflicts_other, seen = [], set()
    for p, n in ask:
        if p not in unowned or p in seen:
            continue
        seen.add(p)
        e = fs_entry(p)
        rec = {'path': p, 'package': n, 'type': e['type'], 'sha256': e['sha256'], 'mode': e['mode'],
               'uid': e['uid'], 'gid': e['gid'], 'mtime_ns': e['mtime_ns'], 'size': e['size'], 'target': e['target']}
        # 'conflicts' (held/reinstated by pkg.py) are regular files per the schema; anything else is reported
        # separately (pacman will refuse the install on it: safe, visible).
        (conflicts if e['type'] == 'f' else conflicts_other).append(rec)

    krels = {c.kernel_release()}
    unit_names = set(cfg.get('writer_units', [])) | {CLEANUP_UNIT}
    backup_abs, payload_etc = set(), set()
    for n in db:
        backup_abs |= {'/' + b for b in db[n]['backup']}
        for f in db[n]['files']:
            mk = MODULES_RE.match(f)
            if mk:
                krels.add(mk.group(1))
            mu = UNIT_RE.match(f)
            if mu:
                unit_names.add(mu.group(1))
    for a in archives.values():
        backup_abs |= {'/' + b for b in a['pkginfo'].get('backup', [])}
        for m in a['members']:
            mk = MODULES_RE.match(m['name'])
            if mk:
                krels.add(mk.group(1))
            mu = UNIT_RE.match(m['name'])
            if mu:
                unit_names.add(mu.group(1))
            if m['name'].startswith('etc/') and m['type'] != 'd':
                payload_etc.add('/' + m['name'])

    # -- module trees
    running = c.kernel_release()
    modules, run_rows = {}, None
    for k in sorted(krels):
        modules[k], rows = module_record(k)
        if k == running:
            run_rows = rows
    rk = modules[running]
    c.need(rk['present'], 'running kernel module tree missing: /usr/lib/modules/' + running)
    copy_tree = bool(set(rk['owned_by']) & set(cand))

    # -- ESP + /etc scans
    esp_files, esp_dirs, esp_excl = walk_esp(ctx.esp)
    esp_bytes = sum(s.st_size for s in esp_files.values())
    explicit, roots = etc_plan(cfg, backup_abs, payload_etc)
    etc = etc_scan(explicit, roots)
    etc_bytes = sum(e['size'] for e in etc.values() if e['type'] == 'f')
    need_root = esp_bytes + etc_bytes + (rk['bytes'] if copy_tree else 0) + int(cfg.get('root_reserve_bytes',
                                                                                         2 << 30))
    free_root = root_free(ctx)
    c.need(free_root >= need_root, 'root free %d < copies + reserve %d' % (free_root, need_root))
    esp_free0 = esp_free(ctx)

    try:
        os.mkdir(part, 0o700)
        result = _copy_and_finish(ctx, part, esp_files, esp_dirs, esp_excl, etc, roots, rk, run_rows,
                                  copy_tree, running, cand)
        state = {
            'schema': SCHEMA, 'run_id': cfg['run_id'], 'run8': run8(ctx), 'device': cfg['device'],
            'boot_id': c.boot_id(), 'kernel': running, 'board': c.board(), 'cmdline': c.cmdline(),
            'captured_at': time.time(),
            'packages_all': packages_all, 'packages': packages, 'backup_files': sorted(backup_abs),
            'modules': modules, 'modules_dir': modules_listing(),
            'running_kernel': {'krel': running, 'owned_by': rk['owned_by'],
                               'copy': ('capture/modules/%s.tar' % running) if copy_tree else None,
                               'copy_sha256': result.pop('tar_sha256')},
            'esp': {'root': cfg.get('esp', c.ESP_DEFAULT), 'free': esp_free0, 'usage': esp_usage(ctx.esp),
                    'cluster': esp_cluster(ctx.esp), 'excluded': ESP_EXCLUDED, 'files': result.pop('esp_manifest'),
                    'dirs': sorted(esp_dirs), 'info': result.pop('esp_info')},
            'menu': result.pop('menu'), 'bootbin_sha256': result.pop('bootbin'),
            'etc': etc, 'etc_roots': sorted(roots),
            'units': {u: unit_props(u) for u in sorted(unit_names)},
            'systemd_etc': systemd_etc(), 'efivars': efivars(), 'snapshots': snapshots(),
            'machine_id': machine_id(), 'conflicts': conflicts, 'conflicts_other': conflicts_other,
            'known_good_refs': known_good_refs(),
            'originals_verified': originals_verified,
            'copies': {'esp': 'capture/esp', 'etc': 'capture/etc'},
        }
        state['limine_history'] = limine_history(state['esp']['files'])
        _drift_guard(ctx, state, etc, explicit, roots)
        data = c.dump(state)
        c.write_new(part / 'state.json', data)
        c.fsync_dir(part)
        os.rename(part, final)
        c.fsync_dir(ctx.run_dir)
    except BaseException:
        if os.path.lexists(part):
            shutil.rmtree(part, ignore_errors=True)
        raise
    got = c.sha_file(final / 'state.json')[0]
    c.need(got == c.H(data), 'state.json readback mismatch')
    d = state['menu']['default']
    return {'capture_sha256': got, 'state_bytes': len(data),
            'esp': {'files': len(state['esp']['files']), 'bytes': esp_bytes, 'free': esp_free0,
                    'manifest_sha256': c.H(json_bytes(state['esp']['files']))},
            'etc': {'entries': len(etc), 'copied': result['etc_copied'],
                    'manifest_sha256': c.H(json_bytes(etc))},
            'menu_sha256': state['menu']['sha256'],
            'default_entry': {k: d[k] for k in ('name', 'path', 'uki_sha256', 'auto_entry', 'owned_by_package_uki')},
            'running_kernel': state['running_kernel'],
            'modules': {k: {'present': v['present'], 'tree_sha256': v['tree_sha256'], 'owned_by': v['owned_by']}
                        for k, v in modules.items()},
            'conflicts': conflicts, 'conflicts_other': conflicts_other, 'originals_verified': originals_verified,
            'units': len(state['units']), 'snapshots': len(state['snapshots'])}


def _copy_and_finish(ctx, part, esp_files, esp_dirs, esp_excl, etc, roots, rk, run_rows, copy_tree, running,
                     cand):
    out = {}
    # ESP byte copies (manifest sha = the bytes we copied; copy re-read and compared)
    ed = part / 'esp'
    os.mkdir(ed, 0o700)
    for rel in sorted(esp_dirs):
        os.mkdir(ed / rel, 0o700)
    manifest = {}
    for rel, st in sorted(esp_files.items()):
        sha, _, n = copy_file(ctx.esp / rel, ed / rel)
        c.need(n == st.st_size, 'ESP file changed during capture: ' + rel)
        c.need(c.sha_file(ed / rel)[0] == sha, 'capture copy readback mismatch: ' + rel)
        os.utime(ed / rel, ns=(st.st_atime_ns, st.st_mtime_ns))
        manifest[rel] = {'size': n, 'sha256': sha, 'mtime_ns': st.st_mtime_ns}
    for d in [ed] + [ed / r for r in esp_dirs]:
        c.fsync_dir(d)
    info = {'ubootefi.var': None, 'excluded_files': {}}
    for rel, st in sorted(esp_excl.items()):
        rec = {'type': ftype(st), 'size': st.st_size}
        if rel.lower().startswith('ubootefi.var') and stat.S_ISREG(st.st_mode):
            rec['sha256'] = c.sha_file(ctx.esp / rel)[0]
            if rel == 'ubootefi.var':
                info['ubootefi.var'] = rec['sha256']
        info['excluded_files'][rel] = rec
    out['esp_manifest'], out['esp_info'] = manifest, info

    # menu + default entry (must agree with the copied bytes)
    raw, _, dinfo = analyse_default(ctx.esp, set(cand))
    c.need('limine.conf' in manifest and c.H(raw) == manifest['limine.conf']['sha256'],
           'limine.conf changed during capture')
    c.need(dinfo['path'] in manifest and manifest[dinfo['path']]['sha256'] == dinfo['uki_sha256'],
           'default UKI not in ESP manifest or changed during capture')
    out['menu'] = {'sha256': c.H(raw), 'bytes': len(raw), 'default': dinfo, 'lab_block_sha256':
                   c.H(lab_block(raw).encode()) if lab_block(raw) is not None else None}
    bb = manifest.get('m1n1/boot.bin')
    out['bootbin'] = bb['sha256'] if bb else None

    # /etc copies
    xd = part / 'etc'
    os.mkdir(xd, 0o700)
    copied = 0
    for p, e in sorted(etc.items()):
        if e['type'] != 'f':
            continue
        dst = xd / p.lstrip('/')
        makedirs(dst.parent)
        sha, _, n = copy_file(c.P(p), dst)
        c.need(sha == e['sha256'] and n == e['size'], '/etc file changed during capture: ' + p)
        c.need(c.sha_file(dst)[0] == sha, 'capture copy readback mismatch: ' + p)
        copied += 1
    out['etc_copied'] = copied

    # running kernel module tree copy (only when a candidate owns it, i.e. the install replaces it)
    out['tar_sha256'] = None
    if copy_tree:
        md = part / 'modules'
        os.mkdir(md, 0o700)
        dest = md / (running + '.tar')
        live = c.P('/usr/lib/modules/' + running)
        tar_tree(live, running, dest)
        c.fsync_dir(md)
        if tree_rows is local_tree_rows:
            live_rows = run_rows
        else:   # shared definition in common.py: verify the copy format-independently, re-check the live sha
            live_rows = local_tree_rows(live)
            c.need(tree_sha(tree_rows(live)) == rk['tree_sha256'], 'module tree changed during capture')
        c.need(tar_rows(dest, running) == live_rows,
               'module tree tar does not reproduce the live tree (changed during capture?)')
        out['tar_sha256'] = c.sha_file(dest)[0]
    return out


def _drift_guard(ctx, state, etc, explicit, roots):
    """Refuse if anything we captured moved underneath us (writers are not held yet at capture time)."""
    drift = esp_drift(ctx.esp, state)
    raw = c.read_small(ctx.esp / 'limine.conf', 1 << 20)
    if c.H(raw) != state['menu']['sha256']:
        drift.append('limine.conf bytes')
    again = etc_scan(explicit, roots)
    if again != etc:
        drift.append('/etc capture set: ' + ', '.join(sorted(p for p in set(again) | set(etc)
                                                              if again.get(p) != etc.get(p)))[:500])
    c.need(not drift, 'system changed during capture: ' + '; '.join(drift[:20]))
