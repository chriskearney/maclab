# ---------------------------------------------------------------- ESP

def esp_excluded(rel):
    top = rel.split('/', 1)[0].lower()
    if top == 'maclab':
        return True
    return '/' not in rel and fnmatch.fnmatchcase(rel.lower(), 'ubootefi.var*')


def walk_esp(esp):
    """-> files {rel: stat}, dirs [rel], excluded {rel: stat} (excluded = lab-agent owned, info only)."""
    files, dirs, excluded = {}, [], {}

    def rec(d, prefix, excl):
        for e in sorted_scandir(d):
            rel = prefix + e.name
            st = os.lstat(e.path)
            if excl or esp_excluded(rel):
                if stat.S_ISDIR(st.st_mode):
                    rec(e.path, rel + '/', True)
                else:
                    excluded[rel] = st
                continue
            if stat.S_ISDIR(st.st_mode):
                dirs.append(rel)
                rec(e.path, rel + '/', False)
            elif stat.S_ISREG(st.st_mode):
                files[rel] = st
            else:
                raise c.Refused('unexpected ESP entry type (%s): %s' % (ftype(st), rel))
    rec(str(esp), '', False)
    return files, dirs, excluded


def esp_cluster(esp):
    try:
        s = os.statvfs(esp)
        return s.f_frsize or s.f_bsize or 4096
    except OSError:
        return 4096


def alloc(n, cl):
    return -(-n // cl) * cl


def esp_usage(esp):
    files, _, excl = walk_esp(esp)
    cl = esp_cluster(esp)
    return sum(alloc(s.st_size, cl) for s in list(files.values()) + [x for x in excl.values()
                                                                     if stat.S_ISREG(x.st_mode)])


def esp_free(ctx, state=None):
    """ESP free bytes. Real: statvfs. Tests: config.test_esp_free (free at capture) minus growth since capture."""
    base = test_override(ctx, 'test_esp_free')
    if base is not None:
        if state is not None:
            base -= esp_usage(ctx.esp) - state['esp']['usage']
        return base
    s = os.statvfs(ctx.esp)
    return s.f_bavail * s.f_frsize


# ESP files the running system rewrites on every boot: systemd-boot-random-seed.service refreshes
# loader/random-seed at each start. After a reboot only their presence and size are compared, and esp-restore
# leaves them alone (copying an old seed back would only be refreshed again).
BOOT_REFRESHED = ('loader/random-seed',)


def boot_refreshed(rel, state, live_st, man_row):
    """True when rel is a per-boot file, the Mac has booted since the capture, and only content/mtime differ."""
    return (rel.lower() in BOOT_REFRESHED and c.boot_id() != state.get('boot_id')
            and live_st is not None and stat.S_ISREG(live_st.st_mode) and live_st.st_size == man_row['size'])


def esp_drift(esp, state):
    """Cheap check (set + size + mtime) that the ESP still matches the capture manifest."""
    files, dirs, _ = walk_esp(esp)
    man = state['esp']['files']
    out = []
    for rel in sorted(set(files) | set(man)):
        if rel not in files:
            out.append('missing ' + rel)
        elif rel not in man:
            out.append('extra ' + rel)
        elif rel == 'limine.conf':
            # by bytes: limine-snapper-sync (and the lab agent's job cleanup) rewrite it with identical bytes
            if files[rel].st_size != man[rel]['size'] or c.sha_file(esp / rel)[0] != man[rel]['sha256']:
                out.append('changed ' + rel)
        elif boot_refreshed(rel, state, files[rel], man[rel]):
            continue        # rebooted since the capture (the fresh-baseline job): the per-boot seed was rewritten
        elif files[rel].st_size != man[rel]['size'] or files[rel].st_mtime_ns != man[rel]['mtime_ns']:
            out.append('changed ' + rel)
    if set(dirs) != set(state['esp']['dirs']):
        out.append('directory set changed')
    return out


# ---------------------------------------------------------------- trees (module dirs)

def tree_row(path, st):
    """One tree row: type, mode, uid, gid (+ size, sha256 for files; target for symlinks). Never follows."""
    r = {'mode': stat.S_IMODE(st.st_mode), 'uid': st.st_uid, 'gid': st.st_gid}
    if stat.S_ISLNK(st.st_mode):
        r.update(type='l', target=os.readlink(path))
    elif stat.S_ISDIR(st.st_mode):
        r['type'] = 'd'
    elif stat.S_ISREG(st.st_mode):
        h, n = c.sha_file(path)
        r.update(type='f', size=n, sha256=h)
    else:
        raise c.Refused('unexpected object type in module tree: %s' % path)
    return r


def walk_tree(root):
    """Yield (rel, path, stat) sorted, root first ('.'); never follows symlinks."""
    st = os.lstat(root)
    yield '.', str(root), st
    if not stat.S_ISDIR(st.st_mode):
        return

    def rec(d, prefix):
        for e in sorted_scandir(d):
            s = os.lstat(e.path)
            rel = prefix + e.name
            yield rel, e.path, s
            if stat.S_ISDIR(s.st_mode):
                yield from rec(e.path, rel + '/')
    yield from rec(str(root), '')


def local_tree_rows(root):
    """{relpath: row} for every entry under root incl. '.' (root itself must be a real directory)."""
    c.need(stat.S_ISDIR(os.lstat(root).st_mode), 'not a directory: %s' % root)
    return {rel: tree_row(p, s) for rel, p, s in walk_tree(root)}


def local_tree_sha(rows):
    """Canonical JSON of the rows sorted by relpath (identical to pkg.py's tree_sha)."""
    return c.H(json.dumps(rows, sort_keys=True, separators=(',', ':')).encode())


# One definition for capture, audit and pkg.py: a shared common.tree_rows/tree_sha wins when present
# (pkg.py does the same lookup), otherwise the byte-compatible local definitions above.
tree_rows = getattr(c, 'tree_rows', None) or local_tree_rows
tree_sha = getattr(c, 'tree_sha', None) or local_tree_sha


def tree_map(root):
    rows = tree_rows(root)
    total = sum(r.get('size') or 0 for r in rows.values() if r.get('type') == 'f')
    return {'tree_sha256': tree_sha(rows), 'entries': len(rows), 'bytes': total}, rows


def tar_tree(root, krel, dest):
    """Tar the tree with numeric owners (no hardlink folding, no symlink follow); fsync."""
    fd = os.open(dest, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_CLOEXEC, 0o600)
    with os.fdopen(fd, 'wb') as f:
        with tarfile.open(fileobj=f, mode='w', format=tarfile.PAX_FORMAT) as t:
            for rel, path, st in walk_tree(root):
                ti = tarfile.TarInfo(krel if rel == '.' else krel + '/' + rel)
                ti.mode = stat.S_IMODE(st.st_mode)
                ti.uid, ti.gid, ti.uname, ti.gname = st.st_uid, st.st_gid, '', ''
                ti.mtime = st.st_mtime
                kind = ftype(st)
                if kind == 'd':
                    ti.type = tarfile.DIRTYPE
                    t.addfile(ti)
                elif kind == 'l':
                    ti.type, ti.linkname = tarfile.SYMTYPE, os.readlink(path)
                    t.addfile(ti)
                elif kind == 'f':
                    ti.type, ti.size = tarfile.REGTYPE, st.st_size
                    sfd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC)
                    with os.fdopen(sfd, 'rb') as src:
                        t.addfile(ti, src)
                else:
                    raise c.Refused('unsupported entry in module tree: %s' % path)
        f.flush()
        os.fsync(f.fileno())


def tar_rows(path, krel):
    """Re-read a tree tar into local_tree_rows() form (format-independent verification of the copy)."""
    rows = {}
    with tarfile.open(path, 'r:') as t:
        for m in t:
            name = m.name
            if name == krel:
                rel = '.'
            else:
                c.need(name.startswith(krel + '/'), 'foreign member in module tar: ' + name)
                rel = name[len(krel) + 1:]
            r = {'mode': m.mode & 0o7777, 'uid': m.uid, 'gid': m.gid}
            if m.isreg():
                h = hashlib.sha256()
                fo = t.extractfile(m)
                while True:
                    b = fo.read(1 << 20)
                    if not b:
                        break
                    h.update(b)
                r.update(type='f', size=m.size, sha256=h.hexdigest())
            elif m.isdir():
                r['type'] = 'd'
            elif m.issym():
                r.update(type='l', target=m.linkname)
            else:
                raise c.Refused('unexpected member type in module tar: ' + name)
            c.need(rel not in rows, 'duplicate member in module tar: ' + name)
            rows[rel] = r
    return rows


# ---------------------------------------------------------------- pacman local DB + archives

def db_sections(text):
    out, cur = {}, None
    for line in text.split('\n'):
        if len(line) > 2 and line.startswith('%') and line.endswith('%'):
            cur = line
            out.setdefault(cur, [])
        elif cur is not None and line != '':
            out[cur].append(line)
    return out


def local_db(name, version):
    """Installed package record straight from the local DB: files, backup, mtree sha (gunzipped)."""
    d = c.P('%s/%s-%s' % (LOCAL_DB, name, version))
    c.need(os.path.isdir(d) and not os.path.islink(d), 'local DB entry missing: %s-%s' % (name, version))
    desc = db_sections(c.read_small(d / 'desc', 16 << 20).decode('utf-8', 'surrogateescape'))
    c.need(desc.get('%NAME%') == [name] and desc.get('%VERSION%') == [version],
           'local DB desc mismatch for %s-%s' % (name, version))
    fs = {}
    if os.path.lexists(d / 'files'):
        fs = db_sections(c.read_small(d / 'files', 256 << 20).decode('utf-8', 'surrogateescape'))
    # libalpm keeps %BACKUP% in 'files'; also accept it in 'desc'.
    backup = sorted({ln.split('\t', 1)[0] for ln in fs.get('%BACKUP%', []) + desc.get('%BACKUP%', [])})
    mtree = None
    if os.path.lexists(d / 'mtree'):
        mtree = c.H(gzip.decompress(c.read_small(d / 'mtree', 256 << 20)))
    return {'files': fs.get('%FILES%', []), 'backup': backup, 'mtree_sha256': mtree}


def all_owned_paths():
    """Every path listed by any installed package (as in the local DB: relative, dirs end with '/')."""
    owned = set()
    root = c.P(LOCAL_DB)
    for e in sorted_scandir(root):
        if not e.is_dir(follow_symlinks=False):
            continue
        f = os.path.join(e.path, 'files')
        if os.path.lexists(f):
            owned.update(db_sections(c.read_small(f, 256 << 20).decode('utf-8', 'surrogateescape'))
                         .get('%FILES%', []))
    return owned


class _HashReader:
    def __init__(self, f):
        self.f, self.h, self.n = f, hashlib.sha256(), 0

    def read(self, size=-1):
        b = self.f.read(size)
        self.h.update(b)
        self.n += len(b)
        return b

    def drain(self):
        while self.read(1 << 20):
            pass


def parse_pkginfo(raw):
    out = {}
    for line in raw.decode('utf-8', 'replace').splitlines():
        if not line.strip() or line.lstrip().startswith('#') or ' = ' not in line:
            continue
        k, v = line.split(' = ', 1)
        out.setdefault(k.strip(), []).append(v.strip())
    return out


def scan_archive(path, hash_payload=False):
    """One streaming pass over a package archive: file sha, .PKGINFO, payload members (+ sha if asked)."""
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC)
    pkginfo, members = {}, []
    with os.fdopen(fd, 'rb') as f:
        r = _HashReader(f)
        with tarfile.open(fileobj=r, mode='r|*') as t:
            for m in t:
                name = m.name
                while name.startswith('./'):
                    name = name[2:]
                name = name.rstrip('/')
                if not name:
                    continue
                c.need(not name.startswith('/') and '..' not in name.split('/'), 'unsafe member name in %s'
                       % path)
                if name in PKG_META:
                    if name == '.PKGINFO':
                        pkginfo = parse_pkginfo(t.extractfile(m).read(1 << 20))
                    continue
                kind = ('f' if m.isreg() else 'd' if m.isdir() else 'l' if m.issym() else
                        'h' if m.islnk() else 'o')
                rec = {'name': name, 'type': kind, 'mode': m.mode & 0o7777, 'uid': m.uid, 'gid': m.gid,
                       'size': m.size if kind == 'f' else None,
                       'target': m.linkname if kind in ('l', 'h') else None}
                if hash_payload and kind == 'f':
                    h = hashlib.sha256()
                    fo = t.extractfile(m)
                    while True:
                        b = fo.read(1 << 20)
                        if not b:
                            break
                        h.update(b)
                    rec['sha256'] = h.hexdigest()
                members.append(rec)
        r.drain()
    return {'sha256': r.h.hexdigest(), 'bytes': r.n, 'pkginfo': pkginfo, 'members': members}


def check_archive_identity(a, entry, kind):
    if entry.get('sha256'):
        c.need(a['sha256'] == entry['sha256'], '%s archive sha mismatch: %s' % (kind, entry['file']))
    pi = a['pkginfo']
    c.need(pi.get('pkgname') == [entry['name']] and pi.get('pkgver') == [entry['version']],
           '%s archive %s is %s %s, config says %s %s' % (kind, entry['file'], pi.get('pkgname'),
                                                         pi.get('pkgver'), entry['name'], entry['version']))


def prove_original(ctx, o, db, a, regen):
    """Every payload member of the original archive must reproduce the live file (backup= excluded)."""
    name = o['name']
    backup = set(db['backup']) | set(a['pkginfo'].get('backup', []))
    arch_list = {m['name'] + ('/' if m['type'] == 'd' else '') for m in a['members']}
    db_list = set(db['files'])
    if arch_list != db_list:
        only_a = sorted(arch_list - db_list)[:10]
        only_d = sorted(db_list - arch_list)[:10]
        raise c.Refused('original archive %s file list != installed %s file list (archive-only %s, '
                        'installed-only %s)' % (o['file'], name, only_a, only_d))
    shas, mismatches, regenerated = {}, [], []
    checked = skipped_backup = 0
    for m in a['members']:
        live = c.P('/' + m['name'])
        st = lst(live)
        kind = m['type']
        if kind == 'd':
            if ftype(st) != 'd':
                mismatches.append('%s: want dir, live %s' % (m['name'], ftype(st)))
            continue
        if kind == 'l':
            if ftype(st) != 'l' or os.readlink(live) != m['target']:
                mismatches.append('%s: symlink differs' % m['name'])
            checked += 1
            continue
        if kind not in ('f', 'h'):
            mismatches.append('%s: unsupported member type' % m['name'])
            continue
        want = m.get('sha256') if kind == 'f' else shas.get(m['target'])
        shas[m['name']] = want
        if m['name'] in backup:
            skipped_backup += 1
            continue
        if ftype(st) != 'f':
            mismatches.append('%s: want file, live %s' % (m['name'], ftype(st)))
            continue
        got = c.sha_file(live)[0]
        if any(fnmatch.fnmatchcase(m['name'], p) for p in regen):
            if got != want:
                regenerated.append('/' + m['name'])
            continue
        if got != want:
            mismatches.append('%s: sha256 differs' % m['name'])
        checked += 1
    c.need(not mismatches, 'original archive %s does not reproduce installed %s: %s'
           % (o['file'], name, '; '.join(mismatches[:20])))
    return {'archive': o['file'], 'archive_sha256': a['sha256'], 'files_checked': checked,
            'backup_skipped': skipped_backup, 'regenerated': regenerated}


def owners_unowned(paths):
    """Subset of abs paths that `pacman -Qqo` says no package owns (batched)."""
    unowned = set()
    for i in range(0, len(paths), 200):
        chunk = paths[i:i + 200]
        r = c.run([c.BIN('pacman'), '-Qqo', '--', *chunk], check=False, timeout=300)
        errs = r.stderr.decode('utf-8', 'surrogateescape').splitlines()
        hits = {ln.split('No package owns ', 1)[1].strip() for ln in errs if 'No package owns ' in ln}
        c.need(r.returncode == 0 or hits, 'pacman -Qqo failed: %s' % '; '.join(errs[-3:]))
        unowned |= hits & set(chunk)
    return unowned


# ---------------------------------------------------------------- /etc capture set

def fs_entry(path_sys, with_sha=True):
    p = c.P(path_sys)
    st = lst(p)
    e = {'type': ftype(st), 'mode': None, 'uid': None, 'gid': None, 'size': None, 'sha256': None,
         'mtime_ns': None, 'target': None}
    if st is None:
        return e
    e.update(mode=stat.S_IMODE(st.st_mode), uid=st.st_uid, gid=st.st_gid, mtime_ns=st.st_mtime_ns)
    if e['type'] == 'f':
        e['size'] = st.st_size
        if with_sha:
            e['sha256'], e['size'] = c.sha_file(p)
    elif e['type'] == 'l':
        e['target'] = os.readlink(p)
        e['size'] = len(os.fsencode(e['target']))
    return e


def etc_scan(explicit, roots):
    """{abs path: entry} for explicit paths (absent allowed) + every member of the recursive roots."""
    out = {p: fs_entry(p) for p in sorted(explicit)}
    for r in sorted(roots):
        if out.get(r, {}).get('type') != 'd':
            continue
        for rel, path, st in walk_tree(c.P(r)):
            if rel != '.':
                out[r + '/' + rel] = fs_entry(r + '/' + rel)
    return out


def etc_plan(cfg, backup_abs, payload_etc):
    """Explicit capture paths + recursive roots (config dirs) derived from config, backup= and payloads."""
    explicit = {p.rstrip('/') for p in cfg.get('etc_capture', [])}
    for p in explicit:
        c.need(p.startswith('/') and '..' not in p.split('/'), 'bad etc_capture path: ' + p)
    siblings = set()
    for p in set(backup_abs) | {p for p in explicit if ftype(lst(c.P(p))) != 'd'}:
        siblings |= {p + '.pacnew', p + '.pacsave'}
    leaf = set(backup_abs) | siblings | set(payload_etc)
    parents = {os.path.dirname(p) for p in leaf} - {'/', '/etc', ''}
    roots = {p for p in explicit if ftype(lst(c.P(p))) == 'd'}
    return explicit | leaf | parents, roots


