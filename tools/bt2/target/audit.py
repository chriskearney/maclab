"""bt2 audit (read-only, exact compare vs capture/state.json) and cleanup.

Modes:
  --held  writers are masked per <run>/writers.json: mask symlinks, held aliases and stopped units are
          expected; everything else (ESP, menu, /etc, packages, trees, ...) must equal the capture exactly.
  final   (default) after release-writers: everything equals the capture; limine.conf may differ ONLY by
          snapshot-subtree additions (same grammar as maclab-air-menu-admission-r1/snapshot_guard.py).
Returns {'mode', 'differences', 'informational'}; any difference => Refused (exit 3; audit never changes
state). The full report is also written to <run>/audit-reports/<mode>.<seq>.json.
"""
import datetime
import json
import os
import re
import shutil
import stat
import sys

import common as c
import limine
import capture as cap
import espops

ABSENT = {'type': 'absent', 'mode': None, 'uid': None, 'gid': None, 'size': None, 'sha256': None,
          'mtime_ns': None, 'target': None}
TITLE_RE = re.compile(r'///([1-9][0-9]{0,9}) │ (20[0-9]{2}-[0-9]{2}-[0-9]{2} [0-9]{2}:[0-9]{2}:[0-9]{2})')
HIST_RE = re.compile(r'boot\(\):/([0-9a-f]{32})/limine_history/([A-Za-z0-9_.-]+\.efi)_sha256_([0-9a-f]{64})'
                     r'#([0-9a-f]{128})')
SNAP_TOKEN = 'rootflags=subvol=/@/.snapshots/{snapshot_id}/snapshot'
SNAP_MARK = '### Auto-generated by limine-snapper-sync'
PLACEHOLDER = '\x00SNAPSHOT_SUBTREE\x00'
REPORT_LIMIT = 96 * 1024     # refused_reason excerpt; stdout must stay <= 256 KiB (full list in audit-reports/)


# ---------------------------------------------------------------- snapshot subtree grammar

class SnapErr(ValueError):
    pass


def sneed(v, msg):
    if not v:
        raise SnapErr('snapshot guard: ' + msg)


def parse_snapshots(raw):
    """-> (static text with the subtree replaced by a placeholder, indent or None, [records])."""
    sneed(isinstance(raw, bytes) and 0 < len(raw) <= 512 * 1024, 'menu type/size')
    sneed(b'\x00' not in raw and b'\r' not in raw, 'NUL/CR in menu')
    try:
        text = raw.decode('utf-8')
    except UnicodeDecodeError:
        raise SnapErr('snapshot guard: non-UTF8 menu')
    lines = text.split('\n')
    heads = [i for i, ln in enumerate(lines) if re.fullmatch(r'\s*//Snapshots', ln)]
    if not heads:
        return text, None, []
    sneed(len(heads) == 1, 'ambiguous snapshot heading')
    i = heads[0]
    ind = lines[i][:len(lines[i]) - len(lines[i].lstrip())]
    sneed(i + 2 < len(lines) and lines[i + 1] == ind + SNAP_MARK, 'missing exact autogenerated snapshot heading')
    m = re.fullmatch(re.escape(ind) + r'comment: ([1-9][0-9]?) snapshots', lines[i + 2])
    sneed(m, 'invalid snapshot count line')
    j, recs = i + 3, []
    for _ in range(int(m.group(1))):
        blk = lines[j:j + 8]
        sneed(len(blk) == 8 and all(ln.startswith(ind) for ln in blk), 'truncated snapshot record')
        b = [ln[len(ind):] for ln in blk]
        t = TITLE_RE.fullmatch(b[0])
        sneed(t, 'invalid snapshot heading/id/timestamp')
        sid, stamp = int(t.group(1)), t.group(2)
        sneed(sid <= 2147483647, 'snapshot ID overflow')
        try:
            datetime.datetime.strptime(stamp, '%Y-%m-%d %H:%M:%S')
        except ValueError:
            raise SnapErr('snapshot guard: impossible timestamp')
        sneed(b[1] == 'comment: timeline', 'record %d is not a timeline record' % sid)
        sneed(b[2].startswith('////') and re.fullmatch(r'[A-Za-z0-9_-]{1,64}', b[2][4:]), 'bad kernel id line')
        kid = b[2][4:]
        kv = re.fullmatch(r'comment: Kernel version: ([A-Za-z0-9_.+-]{1,128})', b[3])
        sneed(kv, 'bad kernel version line')
        sneed(b[4] == 'comment: kernel-id=' + kid and b[5] == 'protocol: efi', 'kernel-id/protocol grammar')
        sneed(b[6].startswith('path: '), 'missing path')
        path = b[6][6:]
        hm = HIST_RE.fullmatch(path)
        sneed(hm and '..' not in hm.group(2), 'snapshot resource grammar')
        sneed(b[7].startswith('cmdline: '), 'missing cmdline')
        cmd = b[7][9:]
        toks = cmd.split()
        sneed(' '.join(toks) == cmd, 'noncanonical commandline')
        needle = 'rootflags=subvol=/@/.snapshots/%d/snapshot' % sid
        sneed(toks.count(needle) == 1, 'snapshot subvolume does not match id %d' % sid)
        sneed(sum(x.startswith('root=') for x in toks) == 1 and sum(x.startswith('rootflags=') for x in toks) == 1,
              'duplicate root/rootflags')
        if recs:
            sneed(recs[-1]['id'] > sid and recs[-1]['timestamp'] >= stamp, 'IDs/timestamps not descending')
        recs.append({'id': sid, 'timestamp': stamp, 'raw': '\n'.join(blk), 'path': path, 'hist': hm.groups(),
                     'template': (kid, kv.group(1), path, ' '.join(SNAP_TOKEN if x == needle else x for x in toks))})
        j += 8
    if j < len(lines) and lines[j].strip():
        sneed(not limine.OPT_RE.match(lines[j]) and not re.match(r'\s*///', lines[j]),
              'uncounted snapshot subtree content')
    return '\n'.join(lines[:i] + [PLACEHOLDER] + lines[j:]), ind, recs


def derived_template(state):
    """Snapshot record template for the captured default auto entry (limine-snapper-sync snapshots it)."""
    d, mid = state['menu']['default'], state.get('machine_id')
    if not (d.get('auto_block') and d.get('kernel_version') and d.get('cmdline') and mid):
        return None
    toks = d['cmdline'].split()
    if toks.count('rootflags=subvol=@') != 1:
        return None
    return (d['leaf'], d['kernel_version'],
            'boot():/%s/limine_history/%s_sha256_%s#%s' % (mid, os.path.basename(d['path']), d['uki_sha256'],
                                                           d['uki_b2']),
            ' '.join(SNAP_TOKEN if t == 'rootflags=subvol=@' else t for t in toks))


def snapshot_additions(ref, cur, state):
    """Accept cur only if it equals ref except for newer snapshot records added at the front."""
    rs, rind, old = parse_snapshots(ref)
    cs, cind, new = parse_snapshots(cur)
    sneed(rind is not None, 'captured menu has no snapshot subtree (no anchor): menu must be byte-identical')
    sneed(cind is not None, 'snapshot subtree disappeared')
    sneed(rind == cind, 'snapshot subtree indentation changed')
    sneed(rs == cs, 'non-snapshot bytes changed (default/kernel/resource/lab block/other config)')
    old_ids, new_ids = [r['id'] for r in old], [r['id'] for r in new]
    removed = [x for x in old_ids if x not in new_ids]
    sneed(not removed, 'captured snapshot records removed: %s' % removed)
    k = len(new_ids) - len(old_ids)
    sneed(new_ids[k:] == old_ids, 'additions are not an ordered front prefix')
    added = new[:k]
    for r in added:
        sneed(r['id'] > old_ids[0] and r['timestamp'] >= old[0]['timestamp'], 'snapshot %d not newer than the '
              'captured newest' % r['id'])
    for a, b in zip(old, new[k:]):
        sneed(a['raw'] == b['raw'], 'retained snapshot %d bytes changed' % a['id'])
    allowed = {r['template'] for r in old}
    der = derived_template(state)
    if der:
        allowed.add(der)
    for r in added:
        sneed(r['template'] in allowed, 'added snapshot %d does not match a captured kernel/path/cmdline template'
              % r['id'])
        sneed(state.get('machine_id') in (None, r['hist'][0]), 'added snapshot %d machine-id mismatch' % r['id'])
    return {'added_ids': [r['id'] for r in added], 'captured_count': len(old), 'live_count': len(new),
            'paths': sorted({r['path'] for r in added})}


# ---------------------------------------------------------------- audit

def _cmp(want, live, keys):
    return [k for k in keys if want.get(k) != live.get(k)]


ETC_KEYS = ('type', 'mode', 'uid', 'gid', 'size', 'sha256', 'mtime_ns', 'target')


def audit(ctx):
    held = bool(getattr(ctx, 'held', False)) or '--held' in sys.argv[4:]
    mode = 'held' if held else 'final'
    st = cap.load_state(ctx)
    w = cap.load_writers(ctx) or {}
    D, I = [], []

    def diff(item, path=None, **kw):
        D.append({'item': item, 'path': path, **kw})

    def info(item, path=None, **kw):
        I.append({'item': item, 'path': path, **kw})

    # -- identity / boot
    kr = c.kernel_release()
    if kr != st['kernel']:
        diff('kernel', capture=st['kernel'], live=kr)
    if c.board() != st['board']:
        diff('board', capture=st['board'], live=c.board())
    if 'maclab.job=' in c.cmdline():
        diff('cmdline_job_tag', live=c.cmdline())
    info('boot_id', capture=st['boot_id'], live=c.boot_id())
    if os.path.lexists(c.P('/var/lib/pacman/db.lck')):
        diff('pacman_db_lock_present', '/var/lib/pacman/db.lck')

    # -- packages
    live_all = c.pacman_all()
    for n in sorted(set(live_all) | set(st['packages_all'])):
        if live_all.get(n) != st['packages_all'].get(n):
            diff('package', n, capture=st['packages_all'].get(n), live=live_all.get(n))
    for n, rec in sorted(st['packages'].items()):
        v = live_all.get(n)
        if v != rec['version']:
            diff('named_package_version', n, capture=rec['version'], live=v)
        elif v is not None:
            m = cap.local_db(n, v)['mtree_sha256']
            if m != rec['mtree_sha256']:
                diff('named_package_mtree', n, capture=rec['mtree_sha256'], live=m)

    # -- module trees
    for k, rec in sorted(st['modules'].items()):
        lv, _ = cap.module_record(k)
        bad = _cmp(rec, lv, ('present', 'type', 'owned_by', 'keep_marker', 'tree_sha256', 'entries'))
        if bad:
            diff('module_tree', '/usr/lib/modules/' + k, fields=bad, capture={x: rec.get(x) for x in bad},
                 live={x: lv.get(x) for x in bad})
    now, then = set(cap.modules_listing()), set(st.get('modules_dir', []))
    for name in sorted(now - then):
        if name == '.old':
            info('modules_old_dir', '/usr/lib/modules/.old', live=sorted(os.listdir(c.P('/usr/lib/modules/.old'))))
        elif name.startswith('.bt2-hold-'):
            diff('bt2_module_hold_residue', '/usr/lib/modules/' + name)
        else:
            diff('module_dir_added', '/usr/lib/modules/' + name)
    for name in sorted(then - now):
        (info if name == '.old' else diff)('module_dir_removed', '/usr/lib/modules/' + name)
    if '.old' in now & then:
        info('modules_old_dir', '/usr/lib/modules/.old', live=sorted(os.listdir(c.P('/usr/lib/modules/.old'))))

    # -- ESP + menu
    allowed_new = _audit_esp(ctx, st, mode, diff, info)

    # -- /etc capture set (+ writer hold expectations)
    masks = {m.get('path') or '/etc/systemd/system/' + m['unit'] for m in w.get('masks', [])}
    aliases = {a.get('path') or '/etc/systemd/system/' + a['unit']: a for a in w.get('aliases', [])}
    writer_dirs = {os.path.dirname(p) for p in masks | set(aliases)}
    live_etc = espops.etc_live(st)
    for p in sorted(set(live_etc) | set(st['etc'])):
        want, lv = st['etc'].get(p, ABSENT), live_etc.get(p) or cap.fs_entry(p)
        if held and p in masks:
            if not (lv['type'] == 'l' and lv['target'] == '/dev/null'):
                diff('writer_mask_missing', p, live=lv)
            continue
        if held and p in aliases:
            if lv['type'] != 'absent':
                diff('writer_alias_not_held', p, live=lv)
            continue
        bad = _cmp(want, lv, ETC_KEYS)
        if not bad:
            continue
        if bad == ['mtime_ns'] and want['type'] == 'd' and p in writer_dirs:
            info('dir_mtime_changed_by_writer_hold', p, capture=want['mtime_ns'], live=lv['mtime_ns'])
            continue
        diff('etc', p, fields=bad, capture={x: want.get(x) for x in bad}, live={x: lv.get(x) for x in bad})
    if held:
        for p, a in sorted(aliases.items()):
            hp = cap.held_path(ctx, a['held'])
            s = cap.lst(hp)
            if s is None or not stat.S_ISLNK(s.st_mode) or s.st_ino != a.get('ino') or \
                    os.readlink(hp) != a.get('target'):
                diff('writer_alias_hold_link', str(a['held']), expected={'ino': a.get('ino'), 'target': a.get('target')})

    # -- /etc/systemd/system listing (type, target, inode)
    # pacman replaces every file it (re)installs and etc-restore restores by temp+rename, so those entries cannot
    # keep their inode; their bytes/mode/owner/mtime are compared exactly through the /etc capture set above. The
    # inode stays a hard requirement for everything else: the writer alias (re-linked by hard link), conflicts
    # (reinstated by rename) and every entry nothing in bt2 rewrote.
    live_se = cap.systemd_etc()
    replaced = {f for r in st['packages'].values() for f in r.get('files') or [] if not f.endswith('/')}
    replaced |= _etc_restored(ctx)
    replaced -= set(aliases) | {x['path'] for x in st.get('conflicts', [])}
    for rel in sorted(set(live_se) | set(st['systemd_etc'])):
        p = '/etc/systemd/system/' + rel
        if held and p in masks:
            x = live_se.get(rel) or {}
            if not (x.get('type') == 'l' and x.get('target') == '/dev/null'):
                diff('writer_mask_missing', p, live=x)
            continue
        if held and p in aliases:
            continue
        want, lv = st['systemd_etc'].get(rel), live_se.get(rel)
        if lv != want:
            if p in replaced and p in st['etc'] and want and lv and want['type'] in ('f', 'l') and \
                    (want['type'], want['target']) == (lv['type'], lv['target']):
                info('systemd_etc_inode_replaced', p, capture=want['ino'], live=lv['ino'])
                continue
            diff('systemd_etc', p, capture=want, live=lv)

    # -- units
    mask_units = {m['unit'] for m in w.get('masks', [])}
    stopped = set(w.get('stopped', []))
    for u, want in sorted(st['units'].items()):
        lv = cap.unit_props(u)
        if held and u in mask_units:
            if lv.get('LoadState') != 'masked' or lv.get('ActiveState') != 'inactive':
                diff('writer_unit_not_held', u, live=lv)
            continue
        if held and u in stopped:
            want = dict(want, ActiveState='inactive')
        if lv != want:
            diff('unit', u, capture=want, live=lv)

    # -- efivars, snapshots, conflicts, known-good refs
    for n, present in sorted(cap.efivars().items()):
        if present:
            diff('efivar_present', n)
    snaps = set(cap.snapshots())
    removed = sorted(set(st['snapshots']) - snaps)
    if removed:
        diff('snapshots_removed', '/.snapshots', ids=removed)
    if snaps - set(st['snapshots']):
        info('snapshots_added', '/.snapshots', ids=sorted(snaps - set(st['snapshots'])))
    for x in st['conflicts']:
        lv = cap.fs_entry(x['path'])
        bad = _cmp(x, lv, ('type', 'sha256', 'mode', 'uid', 'gid', 'mtime_ns', 'target'))
        if bad:
            diff('conflict_file', x['path'], fields=bad, capture={k: x.get(k) for k in bad},
                 live={k: lv.get(k) for k in bad})
    kg = cap.known_good_refs()
    for p in sorted(set(kg) | set(st['known_good_refs'])):
        if kg.get(p) != st['known_good_refs'].get(p):
            diff('known_good_ref', p, capture=st['known_good_refs'].get(p), live=kg.get(p))

    res = {'mode': mode, 'differences': D, 'informational': I, 'allowed_new_esp_files': sorted(allowed_new),
           'capture_sha256': c.sha_file(ctx.run_dir / 'capture' / 'state.json')[0]}
    rep = _write_report(ctx, mode, res)
    if D:
        txt = json.dumps(D, sort_keys=True)
        raise c.Refused('audit (%s): %d difference(s) [report %s]: %s' % (mode, len(D), rep,
                                                                        txt[:REPORT_LIMIT]))
    res['report'] = rep
    return res


def _audit_esp(ctx, st, mode, diff, info):
    esp = ctx.esp
    man = st['esp']['files']
    files, dirs, excl = cap.walk_esp(esp)
    live_menu = c.read_small(esp / 'limine.conf', 1 << 20) if 'limine.conf' in files else None
    allowed_new = {}
    menu_changed = live_menu is None or c.H(live_menu) != st['menu']['sha256']
    if menu_changed:
        if mode == 'final' and live_menu is not None:
            ref = c.read_small(ctx.run_dir / 'capture' / 'esp' / 'limine.conf', 1 << 20)
            c.need(c.H(ref) == st['menu']['sha256'], 'capture limine.conf copy corrupt')
            try:
                r = snapshot_additions(ref, live_menu, st)
                info('menu_snapshot_additions', 'limine.conf', **r)
                for p in r['paths']:
                    rel, pin = limine.split_path(p)
                    if rel not in man:
                        allowed_new[rel] = (HIST_RE.fullmatch(p).group(3), pin)
            except SnapErr as e:
                diff('menu', 'limine.conf', capture=st['menu']['sha256'], live=c.H(live_menu), detail=str(e))
        else:
            diff('menu', 'limine.conf', capture=st['menu']['sha256'],
                 live=c.H(live_menu) if live_menu is not None else None)
    if live_menu is not None:
        for ln in live_menu.decode('utf-8', 'replace').split('\n'):
            if ln.strip().startswith('/bt2 original') or ln.strip().startswith('/+bt2 original'):
                diff('bt2_menu_stanza_left', 'limine.conf', line=ln.strip())
    for rel in sorted(set(files) | set(man)):
        if rel == 'limine.conf':
            if not menu_changed and files[rel].st_mtime_ns != man[rel]['mtime_ns']:
                # same bytes, new mtime: a writer (limine-snapper-sync) rewrote it unchanged
                info('menu_rewritten_same_bytes', rel, capture_mtime_ns=man[rel]['mtime_ns'],
                     live_mtime_ns=files[rel].st_mtime_ns)
            continue
        if rel not in files:
            diff('esp_missing', rel)
            continue
        if rel not in man:
            if rel in allowed_new:
                sha, n = c.sha_file(esp / rel)
                if sha == allowed_new[rel][0] and c.b2_file(esp / rel) == allowed_new[rel][1]:
                    info('esp_new_history_file', rel, sha256=sha, bytes=n)
                    continue
            item = 'bt2_fallback_copy_left' if re.fullmatch(r'efi/linux/bt2-[a-z0-9]{8}-original\.efi', rel.lower()) \
                else 'esp_extra'
            diff(item, rel, size=files[rel].st_size)
            continue
        m, s = man[rel], files[rel]
        if cap.boot_refreshed(rel, st, s, m):
            info('esp_boot_refreshed', rel, size=s.st_size, capture_sha256=m['sha256'],
                 live_sha256=c.sha_file(esp / rel)[0], capture_boot_id=st.get('boot_id'), live_boot_id=c.boot_id())
            continue
        sha = c.sha_file(esp / rel)[0] if s.st_size == m['size'] else None
        bad = [k for k, ok in (('size', s.st_size == m['size']), ('sha256', sha == m['sha256']),
                               ('mtime_ns', s.st_mtime_ns == m['mtime_ns'])) if not ok]
        if bad:
            diff('esp_file', rel, fields=bad, capture={k: m[k] for k in bad},
                 live={'size': s.st_size, 'sha256': sha, 'mtime_ns': s.st_mtime_ns})
    for dd in sorted(set(dirs) ^ set(st['esp']['dirs'])):
        if dd in dirs and any(r.startswith(dd + '/') for r in allowed_new) and not any(
                r.startswith(dd + '/') for r in files if r not in allowed_new):
            info('esp_new_history_dir', dd + '/')
            continue
        diff('esp_dir_added' if dd in dirs else 'esp_dir_removed', dd + '/')
    live_bb = c.sha_file(esp / 'm1n1/boot.bin')[0] if 'm1n1/boot.bin' in files else None
    if live_bb != st['bootbin_sha256']:
        diff('bootbin', 'm1n1/boot.bin', capture=st['bootbin_sha256'], live=live_bb)
    # lab-agent owned (excluded): reported, never compared
    cap_ex = st['esp']['info'].get('excluded_files', {})
    for rel in sorted(set(excl) | set(cap_ex)):
        lv = excl.get(rel)
        rec = {'type': cap.ftype(lv), 'size': lv.st_size if lv else None}
        if lv is not None and rel.lower().startswith('ubootefi.var') and stat.S_ISREG(lv.st_mode):
            rec['sha256'] = c.sha_file(esp / rel)[0]
        if lv is None or rec != cap_ex.get(rel):
            info('esp_excluded_changed', rel, capture=cap_ex.get(rel), live=rec if lv else None)
    # free space == capture (+-1 MiB; plus allocations of accepted new history files in final mode)
    cl = st['esp'].get('cluster') or cap.esp_cluster(esp)
    tol = (1 << 20) + sum(cap.alloc(files[r].st_size, cl) for r in allowed_new if r in files)
    free = cap.esp_free(ctx, st)
    if abs(free - st['esp']['free']) > tol:
        diff('esp_free', st['esp']['root'], capture=st['esp']['free'], live=free, tolerance=tol)
    return allowed_new


def _etc_restored(ctx):
    """Paths etc-restore rewrote (temp+rename => new inode), from its ok receipts."""
    out = set()
    rd = ctx.run_dir / 'receipts'
    for f in sorted(os.listdir(rd)):
        if re.fullmatch(r'etc-restore\.\d+\.json', f):
            r = json.loads(c.read_small(rd / f, 16 << 20))
            if r.get('ok') is True:
                out.update(r.get('restored_bytes') or [])
                out.update(r.get('restored_links') or [])
    return out


def _write_report(ctx, mode, res):
    d = ctx.run_dir / 'audit-reports'
    d.mkdir(mode=0o700, exist_ok=True)
    seq = 0
    while os.path.lexists(d / ('%s.%d.json' % (mode, seq))):
        seq += 1
    c.write_new(d / ('%s.%d.json' % (mode, seq)), c.dump(res))
    return 'audit-reports/%s.%d.json' % (mode, seq)


