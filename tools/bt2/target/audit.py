def _hold_refs(ctx):
    """Every hold/ path named in a bt2 receipt or run-dir JSON (writers.json, espops-prep.json, ...)."""
    prefixes = [str(ctx.run_dir / 'hold') + '/', '/var/lib/maclab/bt2/%s/hold/' % ctx.config['run_id'], 'hold/']
    refs = set()

    def walk(v):
        if isinstance(v, dict):
            for x in v.values():
                walk(x)
        elif isinstance(v, list):
            for x in v:
                walk(x)
        elif isinstance(v, str):
            for pre in prefixes:
                if v.startswith(pre) and len(v) > len(pre):
                    refs.add(os.path.normpath(v[len(pre):]))
                    break
    files = [ctx.run_dir / 'receipts' / f for f in sorted(os.listdir(ctx.run_dir / 'receipts'))]
    files += [ctx.run_dir / f for f in sorted(os.listdir(ctx.run_dir)) if f.endswith('.json')]
    for f in files:
        if f.suffix == '.json' and os.path.isfile(f) and not os.path.islink(f):
            try:
                walk(json.loads(c.read_small(f, 16 << 20)))
            except ValueError:
                continue
    return refs


def cleanup(ctx):
    rd = ctx.run_dir / 'receipts'
    seqs = sorted(int(m.group(1)) for f in os.listdir(rd) if (m := re.fullmatch(r'audit\.(\d+)\.json', f)))
    c.need(seqs, 'no audit receipt: run the final audit first')
    last_name = 'audit.%d.json' % seqs[-1]
    last = json.loads(c.read_small(rd / last_name, 16 << 20))
    c.need(last.get('ok') is True and last.get('mode') == 'final' and last.get('differences') == []
           and last.get('run_id') == ctx.config['run_id'],
           'latest audit receipt (%s) is not an ok final-mode audit' % last_name)
    refs = _hold_refs(ctx)
    hold = ctx.run_dir / 'hold'
    unknown = []
    if os.path.lexists(hold):
        for rel, path, s in cap.walk_tree(hold):
            if rel == '.' or stat.S_ISDIR(s.st_mode):
                continue
            parts = rel.split('/')
            if not any('/'.join(parts[:i]) in refs for i in range(1, len(parts) + 1)):
                unknown.append(rel)
    removed, kept = [], ['capture', 'receipts']
    for name in ('pkgs', 'originals', 'cts'):          # cts: the campaign CTS archive + lists staged by the controller
        p = ctx.run_dir / name
        if os.path.lexists(p):
            ctx.changed = True
            shutil.rmtree(p)
            removed.append(name)
    if os.path.lexists(hold):
        if unknown:
            kept.append('hold')
        else:
            ctx.changed = True
            shutil.rmtree(hold)
            removed.append('hold')
    # The controller pulled this tarball (and retained it on the M5); it is ESP-sized, so drop the Mac copy.
    tarball = ctx.run_dir / 'bt2-capture.tar'
    if os.path.lexists(tarball) and stat.S_ISREG(os.lstat(tarball).st_mode):
        ctx.changed = True
        os.unlink(tarball)
        removed.append('bt2-capture.tar')
    c.fsync_dir(ctx.run_dir)
    return {'removed': removed, 'kept': kept, 'hold_unknown': unknown[:200], 'audit_receipt': last_name}
