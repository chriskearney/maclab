#!/bin/sh
# apply.sh <kernel tree> <codes.json>: adds maclab_chaos to a kernel tree as a
# built-in, for a lab-only branch that lab-loop's nights boot. Commit the
# result on its own branch of the kernel fork and build it with `lab build`;
# never merge it.
#
# Each fault gets a fresh random code, so the cmdline and the kernel log never
# name it. The codes go into the tree (drivers/misc/maclab_chaos_codes.h) and
# into codes.json, which lab-loop --codes reads. Keep codes.json away from the
# judge: it is the answer key.
set -eu
tree=${1:?usage: apply.sh <kernel tree> <codes.json>}
out=${2:?usage: apply.sh <kernel tree> <codes.json>}
here=$(cd "$(dirname "$0")" && pwd)
[ -f "$tree/drivers/misc/Makefile" ] || { echo "$tree is not a kernel tree" >&2; exit 1; }

modes="none marker oops_late panic_late panic_early hang_early hang_late netdown"
h="$tree/drivers/misc/maclab_chaos_codes.h"
{
	echo "/* Generated by maclab tools/chaos/apply.sh: lab-only, never ship. */"
	echo "#define MACLAB_CHAOS_CODES { \\"
} >"$h"
json="{"
for m in $modes; do
	c=$(od -An -N8 -tx1 /dev/urandom | tr -d ' \n')
	printf '\t{ "%s", "%s" }, \\\n' "$c" "$m" >>"$h"
	json="$json\"$m\":\"$c\","
done
echo "}" >>"$h"
printf '%s}\n' "${json%,}" >"$out"

cp "$here/maclab_chaos.c" "$tree/drivers/misc/maclab_chaos.c"
grep -qx 'obj-y += maclab_chaos.o' "$tree/drivers/misc/Makefile" ||
	printf '\n# lab-only fault injection (maclab tools/chaos); never ship\nobj-y += maclab_chaos.o\n' >>"$tree/drivers/misc/Makefile"
echo "added drivers/misc/maclab_chaos.c to $tree; codes in $out"
